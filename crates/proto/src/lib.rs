//! CDDA Voxel Frontend IPC protocol (plan.md §6, Phase 1).
//!
//! Wire format: one frame = u32 little-endian length prefix + one FlatBuffers
//! `Envelope` payload. Every decode runs the FlatBuffers verifier before any
//! table access; corrupt or truncated input is an `Err`, never a panic.
//!
//! The native message types are the flatc object-API types (`HelloT`,
//! `SnapshotT`, `MessageT`, ...), re-exported here so callers never touch
//! the raw generated module.

