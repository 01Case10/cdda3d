#[derive(Debug)]
pub enum ProtoError {
    /// FlatBuffers verifier rejected the buffer (corrupt / truncated /
    /// wrong file identifier).
    InvalidFlatbuffer(flatbuffers::InvalidFlatbuffer),
    /// A frame length prefix exceeded MAX_FRAME_LEN.
    OversizeFrame(u32),
    /// Handshake protocol-version mismatch.
    VersionMismatch {
        ours: u32,
        theirs: u32,
    },
    /// The peer's buffer unpacked to something structurally unusable
    /// (defensive: unpack panics on adversarial-but-verifier-passing input
    /// are converted to this error instead of crashing the process).
    Malformed(String),
    Io(std::io::Error),
}

impl fmt::Display for ProtoError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ProtoError::InvalidFlatbuffer(e) => write!(f, "invalid flatbuffer: {e}"),
            ProtoError::OversizeFrame(n) => {
                write!(f, "frame length {n} exceeds max {MAX_FRAME_LEN}")
            }
            ProtoError::VersionMismatch { ours, theirs } => {
                write!(f, "protocol version mismatch: ours={ours} theirs={theirs}")
            }
            ProtoError::Malformed(m) => write!(f, "malformed message: {m}"),
            ProtoError::Io(e) => write!(f, "io error: {e}"),
        }
    }
}

impl std::error::Error for ProtoError {}

impl From<flatbuffers::InvalidFlatbuffer> for ProtoError {
    fn from(e: flatbuffers::InvalidFlatbuffer) -> Self {
        ProtoError::InvalidFlatbuffer(e)
    }
}

impl From<std::io::Error> for ProtoError {
    fn from(e: std::io::Error) -> Self {
        ProtoError::Io(e)
    }
}

pub type Result<T> = std::result::Result<T, ProtoError>;

/// Encode one message as a FlatBuffers Envelope payload (no length prefix;
/// use [`FrameEncoder`] for the wire form).
pub fn encode_message(msg: &MessageT) -> Vec<u8> {
    let mut fbb = flatbuffers::FlatBufferBuilder::new();
    let env = EnvelopeT {
        message: msg.clone(),
    };
    let off = env.pack(&mut fbb);
    generated::cdda::ipc::finish_envelope_buffer(&mut fbb, off);
    fbb.finished_data().to_vec()
}

/// Decode one Envelope payload. The verifier runs first (inside
/// `root_as_envelope`); unpacking is additionally panic-guarded so a hostile
/// or corrupted buffer can only ever produce `Err`.
pub fn decode_message(buf: &[u8]) -> Result<MessageT> {
    // The flatbuffers 24.3.25 `root()` verifier does NOT check the file
    // identifier, and a corrupted root offset can land on a structurally
    // valid but empty envelope. Both are protocol violations here, so check
    // them explicitly (found by gate test 1.4's bit-flip sweep).
    if buf.len() < 8 || &buf[4..8] != b"CDDA" {
        return Err(ProtoError::Malformed("missing CDDA file identifier".into()));
    }
    let env = generated::cdda::ipc::root_as_envelope(buf)?;
    let unpacked = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| env.unpack()));
    match unpacked {
        Ok(env_t) => match env_t.message {
            MessageT::NONE => Err(ProtoError::Malformed(
                "empty envelope (message NONE)".into(),
            )),
            msg => Ok(msg),
        },
        Err(_) => Err(ProtoError::Malformed(
            "unpack panicked on verifier-passing buffer".into(),
        )),
    }
}

/// Handshake rule: versions must match exactly for Phase 1. (docs/protocol.md
/// reserves the right to relax this to a compatible-range check later; a
/// mismatch is always a clear error + clean exit, never a silent proceed.)
pub fn check_handshake(theirs: u32) -> Result<()> {
    if theirs == PROTOCOL_VERSION {
        Ok(())
    } else {
        Err(ProtoError::VersionMismatch {
            ours: PROTOCOL_VERSION,
            theirs,
        })
    }
}

/// Pack a displayed-field pair the way the cheap path expects: the struct is
